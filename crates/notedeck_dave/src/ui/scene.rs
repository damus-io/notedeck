/// The RTS-style scene view for managing agents
pub struct AgentScene {
    /// Camera/view transform state managed by egui::Scene
    scene_rect: Rect,
    /// Currently selected agent IDs
    pub selected: Vec<SessionId>,
    /// Drag selection state
    drag_select: Option<DragSelect>,
    /// Target camera position for smooth animation
    camera_target: Option<Vec2>,
    /// Animation progress (0.0 to 1.0)
    animation_progress: f32,
    /// A session to center the camera on once the map places it: one just
    /// created isn't on the map until the next frame's layout.
    focus_pending: Option<SessionId>,
    /// Where the map draws every host, project, worktree and session.
    map: EasedLayout,
    /// The hover card last shown, kept while its session's data is unchanged.
    hover_card: Option<HoverCard>,
    /// Which sessions have messaged which, for the map's message lines.
    messages: MessageLines,
}

/// State for box/marquee selection
struct DragSelect {
    start: Pos2,
    current: Pos2,
}

/// Action generated by the scene UI
#[derive(Debug, Clone)]
pub enum SceneAction {
    /// Selection changed
    SelectionChanged(Vec<SessionId>),
    /// Request to spawn a new agent
    SpawnAgent,
    /// Request to delete selected agents
    DeleteSelected,
}

/// Response from scene rendering
#[derive(Default)]
pub struct SceneResponse {
    pub action: Option<SceneAction>,
}

impl SceneResponse {
    pub fn new(action: SceneAction) -> Self {
        Self {
            action: Some(action),
        }
    }
}

impl Default for AgentScene {
    fn default() -> Self {
        Self::new()
    }
}

impl AgentScene {
    pub fn new() -> Self {
        Self {
            scene_rect: Rect::from_min_max(Pos2::new(-500.0, -500.0), Pos2::new(500.0, 500.0)),
            selected: Vec::new(),
            drag_select: None,
            camera_target: None,
            animation_progress: 1.0,
            focus_pending: None,
            map: EasedLayout::default(),
            hover_card: None,
            messages: MessageLines::default(),
        }
    }

    /// Check if an agent is selected
    pub fn is_selected(&self, id: SessionId) -> bool {
        self.selected.contains(&id)
    }

    /// Set selection to a single agent
    pub fn select(&mut self, id: SessionId) {
        self.selected.clear();
        self.selected.push(id);
    }

    /// Add an agent to the selection
    pub fn add_to_selection(&mut self, id: SessionId) {
        if !self.selected.contains(&id) {
            self.selected.push(id);
        }
    }

    /// Clear all selection
    pub fn clear_selection(&mut self) {
        self.selected.clear();
    }

    /// Get the first selected agent (for chat panel)
    pub fn primary_selection(&self) -> Option<SessionId> {
        self.selected.first().copied()
    }

    /// Animate camera to focus on a position
    fn focus_on(&mut self, position: Vec2) {
        self.camera_target = Some(position);
        self.animation_progress = 0.0;
    }

    /// Animate the camera to session `id` once the map has placed it.
    pub fn focus_session(&mut self, id: SessionId) {
        self.focus_pending = Some(id);
    }

    /// Render the scene
    pub fn ui(
        &mut self,
        session_manager: &SessionManager,
        focus_queue: &FocusQueue,
        ui: &mut egui::Ui,
        ctrl_held: bool,
    ) -> SceneResponse {
        let mut response = SceneResponse::default();

        let now = ui.input(|i| i.time);
        let wall = wall_clock();
        let synced = self.map.sync(session_manager, now);
        if synced == Synced::First {
            if let Some(bounds) = self.map.target().bounds() {
                self.scene_rect = bounds.expand(40.0);
            }
        }
        self.messages
            .sync(session_manager, now, wall as u64, synced != Synced::Same);
        if self.map.is_easing(now) {
            ui.ctx().request_repaint();
        }
        if let Some(id) = self.focus_pending.take() {
            if let Some(pos) = self.map.node(id, now) {
                self.focus_on(pos.to_vec2());
            }
        }

        // Update camera animation towards target
        if let Some(target) = self.camera_target {
            if self.animation_progress < 1.0 {
                self.animation_progress += 0.08;
                self.animation_progress = self.animation_progress.min(1.0);

                // Smoothly interpolate scene_rect center towards target
                let current_center = self.scene_rect.center();
                let target_pos = Pos2::new(target.x, target.y);
                let t = ease_out_cubic(self.animation_progress);
                let new_center = current_center.lerp(target_pos, t);

                // Shift the scene_rect to center on new position
                let offset = new_center - current_center;
                self.scene_rect = self.scene_rect.translate(offset);

                ui.ctx().request_repaint();
            } else {
                // Animation complete
                self.camera_target = None;
            }
        }

        // Track interactions from inside the scene closure
        let mut clicked_agent: Option<(SessionId, bool)> = None; // (id, shift_held)
        let mut bg_clicked = false;
        let mut bg_drag_started = false;
        // When the soonest visible node next looks different.
        let mut next_change: Option<f64> = None;

        // Use a local copy of scene_rect to avoid borrow conflict
        let mut scene_rect = self.scene_rect;
        let selected_ids = &self.selected;
        let map = &self.map;
        let hover_card = &mut self.hover_card;
        let titles = &session_manager.card_titles;
        let edges = MapEdges {
            lineage: session_manager.lineage_edges(),
            messages: self.messages.lines(),
        };

        let scene_response =
            egui::Scene::new()
                .zoom_range(ZOOM_RANGE)
                .show(ui, &mut scene_rect, |ui| {
                    Self::draw_areas(ui, map, now);
                    // Over the territories, under the nodes.
                    if let Some(change) = draw_edges(ui, map, &edges, now, wall) {
                        next_change = Some(change);
                    }

                    // Empty space: a click deselects, a drag box-selects.
                    // Registered before the nodes so they sit on top of it
                    // and get their own hovers and clicks.
                    let bg_response = ui.interact(
                        ui.max_rect(),
                        ui.scope_id().with("scene_bg"),
                        Sense::click_and_drag(),
                    );

                    // Draw agents and collect interaction responses
                    // Use sessions_ordered() to match keybinding order (Ctrl+1 = first in order, etc.)
                    for (keybind_idx, session) in
                        session_manager.sessions_ordered().into_iter().enumerate()
                    {
                        // Only agentic sessions are on the map.
                        let Some(center) = map.node(session.id, now) else {
                            continue;
                        };
                        let node = MapNode {
                            id: session.id,
                            keybind_number: keybind_idx + 1,
                            center,
                            satellite: session.subagent_of.is_some(),
                            status: session.status(),
                            code: node_code(shown_title(session, titles)),
                            selected: selected_ids.contains(&session.id),
                            show_keybinding: ctrl_held,
                            queue_priority: focus_queue.get_session_priority(session.id),
                        };
                        let agent_response = Self::draw_agent(ui, &node, now);

                        // Satellites are still dots, whatever their status.
                        if !node.satellite && ui.is_rect_visible(agent_response.rect) {
                            if let Some(change) = RingLook::of(node.status).next_change(now) {
                                next_change = Some(next_change.map_or(change, |c| c.min(change)));
                            }
                        }
                        if agent_response.hovered() {
                            let card = HoverCard::cached(
                                hover_card,
                                session_manager,
                                edges.messages,
                                session,
                            );
                            card.show(&agent_response);
                        }
                        if agent_response.clicked() {
                            let shift = ui.input(|i| i.modifiers.shift);
                            clicked_agent = Some((session.id, shift));
                        }
                    }

                    if bg_response.clicked() && clicked_agent.is_none() {
                        bg_clicked = true;
                    }
                    if bg_response.drag_started() && clicked_agent.is_none() {
                        bg_drag_started = true;
                    }
                });

        // Idle, done and pending scenes don't spin the frame loop.
        if let Some(secs) = next_change {
            ui.ctx()
                .request_repaint_after(std::time::Duration::from_secs_f64(secs));
        }

        // Get the viewport rect for coordinate transforms
        let viewport_rect = scene_response.response.rect;

        self.scene_rect = scene_rect;

        // Process agent click
        if let Some((id, shift)) = clicked_agent {
            if shift {
                self.add_to_selection(id);
            } else {
                self.select(id);
            }
            response = SceneResponse::new(SceneAction::SelectionChanged(self.selected.clone()));
        }

        // Process background click
        if bg_clicked && response.action.is_none() && !self.selected.is_empty() {
            self.selected.clear();
            response = SceneResponse::new(SceneAction::SelectionChanged(Vec::new()));
        }

        // Start drag selection
        if bg_drag_started {
            if let Some(pos) = ui.input(|i| i.pointer.interact_pos()) {
                self.drag_select = Some(DragSelect {
                    start: pos,
                    current: pos,
                });
            }
        }

        // Update drag selection position
        if let Some(drag) = &mut self.drag_select {
            if let Some(pos) = ui.input(|i| i.pointer.interact_pos()) {
                drag.current = pos;
            }
        }

        // Handle keyboard input (only when no text input has focus)
        // Note: N key for spawning agents is handled globally in keybindings.rs
        if !ui.ctx().egui_wants_keyboard_input()
            && ui.input(|i| i.key_pressed(egui::Key::Delete))
            && !self.selected.is_empty()
        {
            response = SceneResponse::new(SceneAction::DeleteSelected);
        }

        // Handle box selection completion
        if let Some(drag) = &self.drag_select {
            if ui.input(|i| i.pointer.primary_released()) {
                // Convert screen-space drag coordinates to scene-space
                // Screen -> Scene: scene_pos = scene_rect.min + (screen_pos - viewport.min) / viewport.size() * scene_rect.size()
                let screen_to_scene = |screen_pos: Pos2| -> Pos2 {
                    let rel = (screen_pos - viewport_rect.min) / viewport_rect.size();
                    scene_rect.min + rel * scene_rect.size()
                };

                let scene_start = screen_to_scene(drag.start);
                let scene_current = screen_to_scene(drag.current);
                let selection_rect = Rect::from_two_pos(scene_start, scene_current);

                self.selected.clear();

                for session in session_manager.iter() {
                    let Some(agent_pos) = self.map.node(session.id, now) else {
                        continue;
                    };
                    if selection_rect.contains(agent_pos) {
                        self.selected.push(session.id);
                    }
                }

                if !self.selected.is_empty() {
                    response =
                        SceneResponse::new(SceneAction::SelectionChanged(self.selected.clone()));
                }

                self.drag_select = None;
            }
        }

        // Draw box selection overlay
        if let Some(drag) = &self.drag_select {
            let rect = Rect::from_two_pos(drag.start, drag.current);
            let painter = ui.painter();
            painter.rect_filled(
                rect,
                0.0,
                Color32::from_rgba_unmultiplied(100, 150, 255, 30),
            );
            painter.rect_stroke(
                rect,
                0.0,
                egui::Stroke::new(
                    notedeck::tokens::STROKE_THIN,
                    Color32::from_rgb(100, 150, 255),
                ),
                egui::StrokeKind::Outside,
            );
        }

        response
    }

    /// Draw the map's hosts, projects and worktrees, outermost first, as
    /// nested territories each a step lighter than the one around it, with
    /// worktrees on a dashed edge. Labels sit at the top inside each circle,
    /// on a halo of the panel colour so they read over the lines drawn
    /// across them.
    fn draw_areas(ui: &egui::Ui, map: &EasedLayout, now: f64) {
        let painter = ui.painter();
        let visuals = ui.visuals();
        let tint = visuals.text_color();
        let edge = visuals.weak_text_color();
        let halo = visuals.panel_fill;
        for (i, area) in map.target().areas.iter().enumerate() {
            let at = map.area(i, now);
            let look = AreaLook::of(area.kind);
            painter.circle_filled(at.center, at.radius, tint.gamma_multiply(AREA_FILL));
            let stroke = egui::Stroke::new(
                notedeck::tokens::STROKE_THIN,
                edge.gamma_multiply(look.edge),
            );
            if area.kind == AreaKind::Worktree {
                dashed_circle(painter, at.center, at.radius, WORKTREE_DASH, 0.0, stroke);
            } else {
                painter.circle_stroke(at.center, at.radius, stroke);
            }

            let mut job = egui::text::LayoutJob::default();
            job.append(
                &area.label,
                0.0,
                egui::TextFormat {
                    font_id: look.font.clone(),
                    color: look.color(visuals),
                    extra_letter_spacing: look.letter_spacing,
                    ..Default::default()
                },
            );
            let galley = painter.layout_job(job);
            let pos = at.center + Vec2::new(-galley.size().x / 2.0, -at.radius + look.inset);
            for offset in HALO_OFFSETS {
                painter.galley_with_override_text_color(pos + offset, galley.clone(), halo);
            }
            painter.galley(pos, galley, tint);
        }
    }

    /// Draw a single session's node and return the interaction Response: a
    /// status ring with the session's code in it, moving as its status does
    /// (see [`RingLook`]), or its Ctrl+N number while Ctrl is held. A
    /// subagent is a small still dot in its status colour.
    fn draw_agent(ui: &mut egui::Ui, node: &MapNode<'_>, now: f64) -> Response {
        let radius = if node.satellite {
            SATELLITE_RADIUS
        } else {
            NODE_RADIUS
        };
        let center = node.center;
        let agent_rect = Rect::from_center_size(center, Vec2::splat(radius * 2.0));
        let code = node.code;
        let response = ui
            .interact(
                agent_rect,
                ui.scope_id().with(("agent", node.id)),
                Sense::click(),
            )
            .on_hover_cursor(egui::CursorIcon::PointingHand);
        response.widget_info(|| egui::WidgetInfo::labeled(egui::Role::Button, true, code));

        let look = RingLook::of(node.status);
        let opacity = look.opacity(now);
        let color = node.status.color().gamma_multiply(opacity);
        let painter = ui.painter();
        let visuals = ui.visuals();

        // Selection: a hairline outside the ring.
        if node.selected {
            painter.circle_stroke(
                center,
                radius + SELECTION_GAP,
                egui::Stroke::new(
                    notedeck::tokens::STROKE_THIN,
                    visuals
                        .text_color()
                        .gamma_multiply(notedeck::tokens::OPACITY_MUTED),
                ),
            );
        }

        if node.satellite {
            painter.circle_filled(center, radius, color);
            return response;
        }

        if look.ripple {
            let t = ((now % RIPPLE_SECS) / RIPPLE_SECS) as f32;
            painter.circle_stroke(
                center,
                radius * (1.0 + t),
                egui::Stroke::new(
                    notedeck::tokens::STROKE_THIN,
                    color.gamma_multiply(0.6 * (1.0 - t)),
                ),
            );
        }

        let core = if response.hovered() {
            visuals.widgets.hovered.bg_fill
        } else {
            visuals.extreme_bg_color
        };
        painter.circle_filled(center, radius, core.gamma_multiply(opacity.max(0.5)));
        if look.glow {
            painter.circle_stroke(
                center,
                radius,
                egui::Stroke::new(GLOW_WIDTH, color.gamma_multiply(0.2)),
            );
        }
        let ring = egui::Stroke::new(RING_WIDTH, color);
        match look.dash {
            Some(dash) => {
                let phase = look.spin.map_or(0.0, |secs| {
                    ((now % secs as f64) / secs as f64) as f32 * std::f32::consts::TAU
                });
                dashed_circle(painter, center, radius, dash, phase, ring);
            }
            None => {
                painter.circle_stroke(center, radius, ring);
            }
        }

        // Focus queue indicator dot (top-right of the ring)
        if let Some(priority) = node.queue_priority {
            let dot_radius = radius * 0.3;
            let dot_offset = Vec2::new(radius * 0.7, -radius * 0.7);
            painter.circle_filled(center + dot_offset, dot_radius, priority.color());
        }

        if node.show_keybinding {
            paint_keybind_hint(ui, center, &node.keybind_number.to_string(), radius);
        } else {
            painter.text(
                center,
                egui::Align2::CENTER_CENTER,
                code,
                egui::FontId::monospace(code_size(code)),
                color,
            );
        }

        response
    }
}

/// The lines the map draws between sessions.
struct MapEdges<'a> {
    lineage: &'a [Edge],
    messages: &'a [MessageLine],
}

/// Draw every edge whose ends are both on the map: lineage edges (handoff,
/// chain link, child tether) and message lines with any packet travelling
/// them. Returns when the soonest visible edge next looks different.
fn draw_edges(
    ui: &egui::Ui,
    map: &EasedLayout,
    edges: &MapEdges<'_>,
    now: f64,
    wall: f64,
) -> Option<f64> {
    let painter = ui.painter();
    let line = ui.visuals().text_color();
    for edge in edges.lineage {
        let (Some(from), Some(to)) = (map.node(edge.from, now), map.node(edge.to, now)) else {
            continue;
        };
        match edge.kind {
            EdgeKind::Handoff => {
                let curve = Curve::bent(from, to);
                let stroke = egui::Stroke::new(EDGE_WIDTH, line.gamma_multiply(HANDOFF_OPACITY));
                curve.stroke(painter, stroke);
                curve.arrowhead(painter, stroke);
            }
            EdgeKind::Chain => {
                painter.line_segment(
                    [from, to],
                    egui::Stroke::new(EDGE_WIDTH, line.gamma_multiply(CHAIN_OPACITY)),
                );
            }
            EdgeKind::Child => {
                dashed_line(
                    painter,
                    from,
                    to,
                    TETHER_DASH,
                    egui::Stroke::new(EDGE_WIDTH, line.gamma_multiply(TETHER_OPACITY)),
                );
            }
        }
    }

    let mut next_change: Option<f64> = None;
    for msg in edges.messages {
        let opacity = msg.opacity(wall);
        if opacity <= 0.0 {
            continue;
        }
        let (Some(from), Some(to)) = (map.node(msg.from, now), map.node(msg.to, now)) else {
            continue;
        };
        let curve = Curve::bent(from, to);
        if !ui.is_rect_visible(curve.bounds()) {
            continue;
        }
        curve.stroke(
            painter,
            egui::Stroke::new(
                EDGE_WIDTH,
                FROM_SESSION_VIOLET.gamma_multiply(MESSAGE_OPACITY * opacity),
            ),
        );
        if let Some(t) = msg.packet(now) {
            // Fades in as it leaves and out as it arrives.
            let alpha = (t * 6.0).min((1.0 - t) * 6.0).min(1.0);
            let at = curve.at(t);
            painter.circle_filled(
                at,
                PACKET_GLOW_RADIUS,
                PACKET_COLOR.gamma_multiply(0.25 * alpha),
            );
            painter.circle_filled(at, PACKET_RADIUS, PACKET_COLOR.gamma_multiply(alpha));
        }
        if let Some(change) = msg.next_change(now, wall, ANIMATION_FRAME_SECS) {
            next_change = Some(next_change.map_or(change, |c| c.min(change)));
        }
    }
    next_change
}

/// A quadratic curve from one node to another, bent to one side of the
/// chord so lines between the same nodes in opposite directions don't
/// overlap.
#[derive(Clone, Copy)]
struct Curve {
    from: Pos2,
    ctrl: Pos2,
    to: Pos2,
}

impl Curve {
    /// Bent perpendicular to the chord by a share of its length, at most
    /// [`MAX_BEND`].
    fn bent(from: Pos2, to: Pos2) -> Self {
        let chord = to - from;
        let len = chord.length();
        let ctrl = if len > 0.0 {
            let bend = (len * BEND).min(MAX_BEND);
            from.lerp(to, 0.5) + chord.rot90() / len * -bend
        } else {
            from
        };
        Self { from, ctrl, to }
    }

    /// The point `t` of the way along, 0 to 1.
    fn at(&self, t: f32) -> Pos2 {
        let u = 1.0 - t;
        let v = self.from.to_vec2() * (u * u)
            + self.ctrl.to_vec2() * (2.0 * u * t)
            + self.to.to_vec2() * (t * t);
        v.to_pos2()
    }

    /// A rect holding the whole curve.
    fn bounds(&self) -> Rect {
        Rect::from_two_pos(self.from, self.to).union(Rect::from_center_size(self.ctrl, Vec2::ZERO))
    }

    /// Stroke the curve as short chords, so it allocates no path.
    fn stroke(&self, painter: &egui::Painter, stroke: egui::Stroke) {
        let mut prev = self.from;
        for i in 1..=CURVE_CHORDS {
            let next = self.at(i as f32 / CURVE_CHORDS as f32);
            painter.line_segment([prev, next], stroke);
            prev = next;
        }
    }

    /// An open arrowhead where the curve meets the edge of its end node.
    fn arrowhead(&self, painter: &egui::Painter, stroke: egui::Stroke) {
        // The curve's distance from its end shrinks towards the end, so
        // bisect for where it crosses the node's ring.
        let reach = NODE_RADIUS + SELECTION_GAP;
        let (mut lo, mut hi) = (0.0_f32, 1.0_f32);
        for _ in 0..16 {
            let mid = (lo + hi) / 2.0;
            if self.at(mid).distance(self.to) > reach {
                lo = mid;
            } else {
                hi = mid;
            }
        }
        let tip = self.at(lo);
        let back = self.at((lo - 0.05).max(0.0));
        let dir = (tip - back).normalized();
        if dir == Vec2::ZERO {
            return;
        }
        for side in [ARROW_SPREAD, -ARROW_SPREAD] {
            let wing = Vec2::angled(dir.angle() + std::f32::consts::PI + side) * ARROW_LENGTH;
            painter.line_segment([tip, tip + wing], stroke);
        }
    }
}

/// Stroke from `from` to `to` as dashes, without allocating a path.
fn dashed_line(painter: &egui::Painter, from: Pos2, to: Pos2, dash: Dash, stroke: egui::Stroke) {
    let len = from.distance(to);
    let period = dash.on + dash.off;
    if len <= 0.0 || period <= 0.0 {
        return;
    }
    let dir = (to - from) / len;
    let mut at = 0.0;
    while at < len {
        let end = (at + dash.on).min(len);
        painter.line_segment([from + dir * at, from + dir * end], stroke);
        at += period;
    }
}

/// What [`AgentScene::draw_agent`] draws for one session.
struct MapNode<'a> {
    id: SessionId,
    /// 1-indexed, shown when Ctrl is held (matches Ctrl+N keybindings).
    keybind_number: usize,
    center: Pos2,
    /// A subagent, drawn as a small dot in orbit around its parent.
    satellite: bool,
    status: AgentStatus,
    /// The short code drawn in the ring (see [`node_code`]).
    code: &'a str,
    selected: bool,
    show_keybinding: bool,
    queue_priority: Option<FocusPriority>,
}

/// How a territory of one [`AreaKind`] is drawn.
struct AreaLook {
    /// Opacity of the edge, against the weak text colour.
    edge: f32,
    font: egui::FontId,
    letter_spacing: f32,
    /// Opacity of the label, against the text colour.
    label: f32,
    /// How far below the circle's top the label starts.
    inset: f32,
}

impl AreaLook {
    fn of(kind: AreaKind) -> Self {
        match kind {
            AreaKind::Host => Self {
                edge: 0.35,
                font: egui::FontId::proportional(11.0),
                letter_spacing: 1.8,
                label: 0.85,
                inset: 8.0,
            },
            AreaKind::Project => Self {
                edge: 0.45,
                font: egui::FontId::monospace(10.0),
                letter_spacing: 0.3,
                label: 0.6,
                inset: 6.0,
            },
            AreaKind::Worktree => Self {
                edge: 0.55,
                font: egui::FontId::monospace(9.0),
                letter_spacing: 0.3,
                label: 0.45,
                inset: 5.0,
            },
        }
    }

    fn color(&self, visuals: &egui::Visuals) -> Color32 {
        visuals.text_color().gamma_multiply(self.label)
    }
}

/// How a node's ring looks and moves for one status: working is a rotating
/// dashed arc, needs-input a soft ripple, error a blink, waiting a slow
/// dashed spin, pending a still dashed ghost, idle and done still with done
/// dimmed.
#[derive(Clone, Copy)]
struct RingLook {
    /// The ring's dash pattern, `None` for a solid ring.
    dash: Option<Dash>,
    /// Seconds per turn of a dashed ring, `None` for a still one.
    spin: Option<f32>,
    /// A ring spreads out from the node and fades.
    ripple: bool,
    /// The node blinks between full and dim.
    blink: bool,
    /// A soft wider ring under the ring.
    glow: bool,
    /// The node's opacity, before any blink.
    base_opacity: f32,
}

/// A dash pattern along a circle, in points.
#[derive(Clone, Copy)]
struct Dash {
    on: f32,
    off: f32,
}

impl RingLook {
    const STILL: Self = Self {
        dash: None,
        spin: None,
        ripple: false,
        blink: false,
        glow: false,
        base_opacity: 1.0,
    };

    fn of(status: AgentStatus) -> Self {
        match status {
            AgentStatus::Working => Self {
                dash: Some(Dash { on: 22.0, off: 6.0 }),
                spin: Some(6.0),
                glow: true,
                ..Self::STILL
            },
            AgentStatus::NeedsInput => Self {
                ripple: true,
                glow: true,
                ..Self::STILL
            },
            AgentStatus::Error => Self {
                blink: true,
                glow: true,
                ..Self::STILL
            },
            AgentStatus::Waiting => Self {
                dash: Some(Dash { on: 3.0, off: 4.0 }),
                spin: Some(12.0),
                ..Self::STILL
            },
            AgentStatus::Pending => Self {
                dash: Some(Dash { on: 3.0, off: 4.0 }),
                base_opacity: 0.4,
                ..Self::STILL
            },
            AgentStatus::Done => Self {
                base_opacity: 0.75,
                ..Self::STILL
            },
            AgentStatus::Idle => Self::STILL,
        }
    }

    /// The node's opacity at `now`.
    fn opacity(&self, now: f64) -> f32 {
        if self.blink && (now / BLINK_SECS) as i64 % 2 == 1 {
            return self.base_opacity * 0.3;
        }
        self.base_opacity
    }

    /// How long until the node looks different, `None` if it never does.
    fn next_change(&self, now: f64) -> Option<f64> {
        if self.spin.is_some() || self.ripple {
            return Some(ANIMATION_FRAME_SECS);
        }
        if self.blink {
            return Some(BLINK_SECS - now % BLINK_SECS);
        }
        None
    }
}

/// Stroke `radius` around `center` as dashes, the pattern rounded so a whole
/// number of dashes closes the circle, starting `phase` radians round. Each
/// dash is a few short chords rather than a path, so drawing one allocates
/// nothing of its own.
fn dashed_circle(
    painter: &egui::Painter,
    center: Pos2,
    radius: f32,
    dash: Dash,
    phase: f32,
    stroke: egui::Stroke,
) {
    use std::f32::consts::TAU;
    let period = dash.on + dash.off;
    let dashes = (TAU * radius / period).round().max(1.0);
    let step = TAU / dashes;
    let on = step * dash.on / period;
    let chords = (on * radius / MAX_CHORD).ceil().max(1.0) as usize;
    let at = |angle: f32| center + Vec2::angled(angle) * radius;
    for i in 0..dashes as usize {
        let start = phase + i as f32 * step;
        let mut prev = at(start);
        for k in 1..=chords {
            let next = at(start + on * k as f32 / chords as f32);
            painter.line_segment([prev, next], stroke);
            prev = next;
        }
    }
}

/// The title a session's node and hover card show: its card's current title
/// when it is titled by a card ref that has been looked up, the ref's word id
/// when it hasn't been yet, else its own title.
pub(super) fn shown_title<'a>(session: &'a ChatSession, titles: &'a CardTitles) -> &'a str {
    match session.details.title_ref() {
        Some(card_ref) => titles
            .get(card_ref)
            .unwrap_or_else(|| card_ref.rsplit('/').next().unwrap_or(card_ref)),
        None => session.details.display_title(),
    }
}

/// The short code a node shows for `title`: the code before its colon (see
/// [`TitleParts`]), else the first four characters of its headline.
pub(super) fn node_code(title: &str) -> &str {
    let parts = TitleParts::split(title);
    if let Some(code) = parts.code {
        return code;
    }
    let headline = parts.headline;
    let end = headline
        .char_indices()
        .nth(FALLBACK_CODE_CHARS)
        .map_or(headline.len(), |(i, _)| i);
    headline[..end].trim_end()
}

/// The font size that fits `code` inside a ring: up to three characters at
/// full size, longer codes smaller.
fn code_size(code: &str) -> f32 {
    (34.0 / code.chars().count().max(1) as f32).clamp(4.5, 9.5)
}

/// Radius a session's circle is drawn at, inside its
/// [`LEAF_RADIUS`](crate::scene_layout::LEAF_RADIUS) slot.
const NODE_RADIUS: f32 = 15.0;
/// Radius a subagent's circle is drawn at, in orbit around its parent.
const SATELLITE_RADIUS: f32 = 5.0;
/// Width of a node's status ring.
const RING_WIDTH: f32 = 1.6;
/// Width of the soft ring under an active node's ring.
const GLOW_WIDTH: f32 = 5.0;
/// How far outside the ring the selection hairline is.
const SELECTION_GAP: f32 = 5.0;
/// Each territory's fill, as an opacity of the text colour. Nested
/// territories stack, so each level reads a step lighter (darker in light
/// mode) than the one around it.
const AREA_FILL: f32 = 0.045;
/// A worktree's dashed edge.
const WORKTREE_DASH: Dash = Dash { on: 2.0, off: 3.0 };
/// Where an area label's halo is drawn, around the label.
const HALO_OFFSETS: [Vec2; 4] = [
    Vec2::new(-1.0, -1.0),
    Vec2::new(1.0, -1.0),
    Vec2::new(-1.0, 1.0),
    Vec2::new(1.0, 1.0),
];
/// The longest chord a dashed circle is drawn with, in points.
const MAX_CHORD: f32 = 3.0;
/// Seconds per needs-input ripple.
const RIPPLE_SECS: f64 = 2.0;
/// Seconds an erroring node stays bright, then dim.
const BLINK_SECS: f64 = 0.5;
/// How often a spinning or rippling node is redrawn: 30 fps is smooth for
/// motion this slow and half the cost of 60.
const ANIMATION_FRAME_SECS: f64 = 1.0 / 30.0;
/// Characters of a title without a code that stand in for one.
const FALLBACK_CODE_CHARS: usize = 4;
/// Zoom range of the map. The low end keeps area labels legible.
const ZOOM_RANGE: std::ops::RangeInclusive<f32> = 0.3..=2.0;

/// Width of every line between sessions.
const EDGE_WIDTH: f32 = 1.0;
/// Opacity of a handoff's curve and arrowhead, against the text colour.
const HANDOFF_OPACITY: f32 = 0.45;
/// Opacity of a chain link's line, against the text colour.
const CHAIN_OPACITY: f32 = 0.22;
/// Opacity of a child's tether, against the text colour.
const TETHER_OPACITY: f32 = 0.35;
/// A child's tether is dotted, so it doesn't read as a chain link.
const TETHER_DASH: Dash = Dash { on: 2.0, off: 3.0 };
/// Opacity of a message line, against its violet, before it fades.
const MESSAGE_OPACITY: f32 = 0.45;
/// How far a curved edge bends, as a share of its length.
const BEND: f32 = 0.22;
/// The most a curved edge bends, in points.
const MAX_BEND: f32 = 60.0;
/// How many chords a curved edge is drawn with.
const CURVE_CHORDS: usize = 24;
/// Length of a handoff arrowhead's wings.
const ARROW_LENGTH: f32 = 5.0;
/// Angle of an arrowhead's wings off the line, in radians.
const ARROW_SPREAD: f32 = 0.5;
/// A packet's dot.
const PACKET_RADIUS: f32 = 2.4;
/// The soft glow around a packet.
const PACKET_GLOW_RADIUS: f32 = 5.0;
/// A packet: a lighter violet than its line, so it reads as a glow.
const PACKET_COLOR: Color32 = Color32::from_rgb(0xD4, 0xC2, 0xFF);

/// Now, in unix seconds with a fraction, for how long ago a message was
/// sent.
fn wall_clock() -> f64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map_or(0.0, |d| d.as_secs_f64())
}

/// Easing function for smooth camera animation
fn ease_out_cubic(t: f32) -> f32 {
    1.0 - (1.0 - t).powi(3)
}

